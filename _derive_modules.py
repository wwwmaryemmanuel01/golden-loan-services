import pathlib

src = pathlib.Path('_vc2js.js').read_text()


def derive(out, header, pack_name, pack_title, ready, filt_map, recon_toast):
    s = src
    s = s.replace('/* ============================================================\n'
                  '   VISA CARD MANAGEMENT & CARD PAYMENTS — page behaviour\n'
                  '   Everything here is defensive: a missing element never throws.\n'
                  '   ============================================================ */',
                  '/* ============================================================\n'
                  '   ' + header + ' — page behaviour\n'
                  '   Everything here is defensive: a missing element never throws.\n'
                  '   ============================================================ */')
    s = s.replace("visacards-export-pack.csv", pack_name)
    s = s.replace("'# Golden Financial Services — VISA card register'", "'" + pack_title + "'")
    s = s.replace("window.__vc2Ready = 1;", "window." + ready + " = 1;")
    for a, b in filt_map:
        s = s.replace(a, b)
    s = s.replace(
        "'Settlement check finished — 18 card movements, every clean line matches the statement'",
        recon_toast)
    pathlib.Path(out).write_text(s)
    print('wrote', out, len(s), 'bytes')


derive('_sb2js.js',
       'STATISTICS & THE NUMBERS OF THE BOOK',
       'statistics-export-pack.csv',
       "# Golden Financial Services — statistics pack",
       '__sb2Ready',
       [("readFilter('kind')", "readFilter('area')"),
        ("readFilter('state')", "readFilter('product')"),
        ("readFilter('type')", "readFilter('branch')")],
       "'Statistics refreshed — every table rebuilt from the ledger, as at close of day'")

derive('_sm2js.js',
       'STATEMENTS & THE PAPER OF RECORD',
       'statements-export-pack.csv',
       "# Golden Financial Services — statement desk pack",
       '__sm2Ready',
       [("readFilter('type')", "readFilter('period')"),
        ("readFilter('officer')", "readFilter('channel')")],
       "'Reconciliation finished — 3 gaps open, the reissues are queued'")

BUILD = '''#!/bin/bash
# Rebuilds {outfile} from the generated partials.
#
# The body is generated by the module generator from the twenty-section
# specification, so every numbered sub-item is present by construction and
# the figures stay consistent across sections.
set -e
cd "$(dirname "$0")"

python3 _gen_{stem}.py
cat _{stem}.css {css2} > {buildcss}
python3 _compose.py {head} {stem} {buildcss}

{{
  cat {head}
  cat {body}
  cat {js}
  printf '</body>\\n</html>\\n'
}} > {outfile}

python3 - <<'PYEOF'
import pathlib
p = pathlib.Path('{outfile}')
s = p.read_text()
s = s.replace('<title>Module — GOLDEN FINANCIAL SERVICES</title>',
              '<title>{title} — GOLDEN FINANCIAL SERVICES</title>')
p.write_text(s)
print('built {outfile}', len(s), 'bytes')
PYEOF

python3 inject_backnav.py {outfile}
'''

for stem, head, css2, buildcss, body, js, title, outfile in (
    ('statistics', '_sbhead.html', '_statistics2.css', '_statistics-build.css', '_sb2body.html', '_sb2js.js',
     'Statistics', 'statistics.html'),
    ('statements', '_smhead.html', '_statements2.css', '_statements-build.css', '_sm2body.html', '_sm2js.js',
     'Statements', 'statements.html')):
    pathlib.Path('build-' + stem + '.sh').write_text(BUILD.format(
        stem=stem, head=head, css2=css2, buildcss=buildcss, body=body, js=js, title=title, outfile=outfile))
    print('wrote build-' + stem + '.sh')
